// Aynı olayda aynı replik art arda gelmesin.
const lastShown = {};
export function pickBotMessage(kind) {
  const pool = BOT_MESSAGES[kind];
  if (!Array.isArray(pool) || pool.length === 0) return null;
  let text = pool[Math.floor(Math.random() * pool.length)];
  if (pool.length > 1 && text === lastShown[kind]) {
    text = pool[(pool.indexOf(text) + 1) % pool.length];
  }
  lastShown[kind] = text;
  return { text, mood: BOT_FACES[kind] || 'neutral', gesture: BOT_GESTURES[kind] || 'shrug' };
}
